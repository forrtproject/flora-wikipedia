#!/usr/bin/env python3
"""Write pages.sql: the cards the shared store accepts (schema.sql refuses any other page_id).

    python3 editing-support/supabase/make_pages_sql.py [BUILT_SITE_DIR]

Reads data/suggestions.json from the built site (default ../flora-wikipedia-edit-prototype-20261006 next to
the repository). Run it, and then pages.sql in the Supabase SQL editor, whenever the set of cards changes.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
built = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / 'flora-wikipedia-edit-prototype-20261006'
pages = json.loads((built / 'data' / 'suggestions.json').read_text())['pages']
q = lambda s: "'" + str(s).replace("'", "''") + "'"
rows = ',\n'.join(f"  ({q(p['page_id'])}, {q(p['page']['title'])})" for p in sorted(pages, key=lambda p: int(p['page_id'])))
(HERE / 'pages.sql').write_text(
    '-- The cards on the review site; generated by make_pages_sql.py. Run after schema.sql.\n'
    f'insert into pages (page_id, title) values\n{rows}\n'
    'on conflict (page_id) do update set title = excluded.title;\n')
print(f'{len(pages)} pages -> {HERE / "pages.sql"}')
